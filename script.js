
/* ==========================================
   GLOBALRESUME AI - RESUME ANALYZER
   Gemini API through Vercel Backend
========================================== */

document.addEventListener("DOMContentLoaded", () => {

    // Find HTML elements using their IDs
    const getElement = (...ids) => {
        for (const id of ids) {
            const element = document.getElementById(id);
            if (element) return element;
        }
        return null;
    };

    // Form elements
    const resumeInput = getElement(
        "resumeText",
        "resumeContent",
        "resume",
        "resumeInput"
    );

    const jobInput = getElement(
        "jobDescription",
        "jobDescriptionInput",
        "job"
    );

    const resumeLanguageInput = getElement("resumeLanguage");
    const outputLanguageInput = getElement("outputLanguage");
    const feedbackLanguageInput = getElement("feedbackLanguage");

    const actionInput = getElement(
        "action",
        "aiAction",
        "analysisType"
    );

    const analyzeButton = getElement(
        "analyzeBtn",
        "analyzeButton",
        "improveBtn"
    );

    const resultsContainer = getElement(
        "results",
        "resultsSection",
        "analysisResults",
        "resultContainer"
    );

    // Results output container
    let output = getElement("aiResults", "aiOutput");

    if (!output && resultsContainer) {
        output = document.createElement("div");
        output.id = "aiResults";
        resultsContainer.appendChild(output);
    }

    // Escape HTML to prevent unsafe HTML insertion
    function escapeHTML(value) {
        return String(value ?? "").replace(/[&<>"']/g, char => ({
            "&": "&amp;",
            "<": "&lt;",
            ">": "&gt;",
            '"': "&quot;",
            "'": "&#039;"
        })[char]);
    }

    // Display status messages
    function showMessage(message, type = "info") {
        let messageBox = getElement("statusMessage");

        if (!messageBox) {
            messageBox = document.createElement("div");
            messageBox.id = "statusMessage";

            if (analyzeButton?.parentElement) {
                analyzeButton.parentElement.appendChild(messageBox);
            }
        }

        if (messageBox) {
            messageBox.textContent = message;
            messageBox.className = "status-message " + type;
        }

        console.log(`[${type.toUpperCase()}] ${message}`);
    }

    // Loading indicator
    function showLoading() {
        if (analyzeButton) {
            analyzeButton.disabled = true;
            analyzeButton.textContent = "Analyzing your resume...";
        }

        if (output) {
            output.innerHTML = `
                <div class="analysis-loading">
                    <div class="loading-spinner"></div>
                    <h3>AI is analyzing your resume</h3>
                    <p>Checking skills, experience and job requirements...</p>
                </div>
            `;
        }

        showMessage("Please wait while Gemini analyzes your resume.");
    }

    // Restore button
    function hideLoading() {
        if (analyzeButton) {
            analyzeButton.disabled = false;
            analyzeButton.textContent = "✨ Improve My Resume";
        }
    }

    // Create safe list items
    function makeList(items) {
        if (!Array.isArray(items) || items.length === 0) {
            return "<li>No information provided.</li>";
        }

        return items.map(item =>
            `<li>${escapeHTML(item)}</li>`
        ).join("");
    }

    // Display analysis results
    function displayResults(data) {

        if (!output) {
            showMessage(
                "Analysis completed, but the HTML results container is missing.",
                "error"
            );
            return;
        }

        const score = Math.max(
            0,
            Math.min(
                100,
                Number(data.match_score ?? data.ats_score ?? 0)
            )
        );

        const summary = data.professional_summary || "";
        const improvedResume = data.improved_resume || "";
        const translatedResume = data.translated_resume || "";

        const strengths = data.strengths || [];
        const corrections = data.grammar_corrections || [];
        const suggestions = data.suggestions || [];

        output.innerHTML = `
            <div class="ai-result-card">

                <div class="result-heading">
                    <span>AI RESUME ANALYSIS</span>
                    <h2>Your Resume Report</h2>
                    <p>Analysis generated by Google Gemini</p>
                </div>

                <div class="score-card">
                    <h3>Resume Match Score</h3>

                    <div class="score-number">
                        ${score}<small>/100</small>
                    </div>

                    <div class="score-track">
                        <div class="score-fill"
                             style="width:${score}%">
                        </div>
                    </div>

                    <p>Estimated match based on the supplied job description.</p>
                </div>

                <div class="result-section">
                    <h3>🌐 Detected Language</h3>
                    <p>${escapeHTML(data.detected_language || "Not specified")}</p>
                </div>

                <div class="result-section">
                    <h3>✨ Professional Summary</h3>
                    <p>${escapeHTML(summary || "No summary returned.")}</p>
                </div>

                <div class="result-section">
                    <h3>💪 Resume Strengths</h3>
                    <ul>${makeList(strengths)}</ul>
                </div>

                <div class="result-section">
                    <h3>✍️ Grammar Corrections</h3>
                    <ul>${makeList(corrections)}</ul>
                </div>

                <div class="result-section">
                    <h3>🚀 Improvement Suggestions</h3>
                    <ul>${makeList(suggestions)}</ul>
                </div>

                <div class="result-section">
                    <h3>📄 Improved Resume</h3>

                    <pre id="improvedResumeText">${escapeHTML(
                        improvedResume || "No improved resume returned."
                    )}</pre>

                    <button type="button" id="copyResumeBtn">
                        Copy Improved Resume
                    </button>

                    <button type="button" id="downloadResumeBtn">
                        Download Resume TXT
                    </button>
                </div>

                ${translatedResume ? `
                    <div class="result-section">
                        <h3>🌍 Translated Resume</h3>
                        <pre>${escapeHTML(translatedResume)}</pre>
                    </div>
                ` : ""}

            </div>
        `;

        // Copy improved resume
        const copyButton = getElement("copyResumeBtn");
        const downloadButton = getElement("downloadResumeBtn");

        copyButton?.addEventListener("click", async () => {
            try {
                await navigator.clipboard.writeText(improvedResume);
                showMessage(
                    "Improved resume copied successfully.",
                    "success"
                );
            } catch (error) {
                showMessage(
                    "Could not copy. Please select and copy the text manually.",
                    "error"
                );
            }
        });

        // Download improved resume
        downloadButton?.addEventListener("click", () => {
            const blob = new Blob([improvedResume], {
                type: "text/plain;charset=utf-8"
            });

            const url = URL.createObjectURL(blob);
            const link = document.createElement("a");

            link.href = url;
            link.download = "Improved_Resume.txt";
            document.body.appendChild(link);
            link.click();
            link.remove();

            URL.revokeObjectURL(url);
        });

        showMessage(
            "Resume analysis completed successfully!",
            "success"
        );

        output.scrollIntoView({
            behavior: "smooth",
            block: "start"
        });
    }

    // Analyze resume using the Vercel backend
    async function analyzeResume() {

        if (!resumeInput) {
            showMessage(
                "Resume input field not found. Check the ID in index.html.",
                "error"
            );
            return;
        }

        const resume = resumeInput.value.trim();
        const jobDescription = jobInput?.value.trim() || "";

        if (resume.length < 30) {
            showMessage(
                "Please enter your resume content before analyzing.",
                "error"
            );
            resumeInput.focus();
            return;
        }

        // Prepare request data
        const requestData = {
            resume: resume,
            jobDescription: jobDescription,

            resumeLanguage:
                resumeLanguageInput?.value || "Auto Detect",

            outputLanguage:
                outputLanguageInput?.value || "English",

            feedbackLanguage:
                feedbackLanguageInput?.value || "English",

            action:
                actionInput?.value || "Complete Resume Improvement"
        };

        showLoading();

        try {

            // Send request to Vercel API
            const response = await fetch("/api/analyze", {
                method: "POST",
                headers: {
                    "Content-Type": "application/json"
                },
                body: JSON.stringify(requestData)
            });

            // Read response
            const contentType =
                response.headers.get("content-type") || "";

            const responseText = await response.text();

            // Diagnostic information for browser console
            console.log("API URL:", response.url);
            console.log("HTTP Status:", response.status);
            console.log("Content Type:", contentType);
            console.log(
                "API Response:",
                responseText.substring(0, 1000)
            );

            // Detect HTML or other non-JSON responses
            if (!contentType.toLowerCase().includes("application/json")) {

                throw new Error(
                    `Vercel returned a non-JSON response (HTTP ${response.status}). Check Vercel Function Logs.`
                );
            }

            // Parse JSON
            let data;

            try {
                data = JSON.parse(responseText);
            } catch (error) {
                throw new Error(
                    "The API returned invalid JSON. Check Vercel Function Logs."
                );
            }

            // Handle backend errors
            if (!response.ok) {
                throw new Error(
                    data.error ||
                    data.detail ||
                    `Server error: HTTP ${response.status}`
                );
            }

            // Display successful results
            displayResults(data);

        } catch (error) {

            console.error("Resume Analyzer Error:", error);

            if (output) {
                output.innerHTML = `
                    <div class="error-card">
                        <h3>Analysis Failed</h3>
                        <p>${escapeHTML(error.message)}</p>
                        <p>
                            Check your Vercel deployment,
                            API configuration and Gemini API settings.
                        </p>
                    </div>
                `;
            }

            showMessage(error.message, "error");

        } finally {
            hideLoading();
        }
    }

    // Connect Analyze button
    if (analyzeButton) {
        analyzeButton.addEventListener("click", analyzeResume);
    } else {
        console.error(
            "Analyze button not found. Check its HTML ID."
        );
    }

    // Support form submission
    const resumeForm = getElement("resumeForm", "analyzeForm");

    if (resumeForm) {
        resumeForm.addEventListener("submit", event => {
            event.preventDefault();
            analyzeResume();
        });
    }

    console.log("GlobalResume AI script loaded successfully.");

});
